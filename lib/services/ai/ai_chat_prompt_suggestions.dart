  /// 从 [all] 中随机抽取 [count] 条互不重复的建议。
  static List<String> pick({int count = displayCount, Random? random}) {
    if (count <= 0) return const [];
    if (count >= all.length) return List<String>.unmodifiable(all);
    final rng = random ?? Random();
    final indices = List<int>.generate(all.length, (i) => i);
    for (var i = 0; i < count; i++) {
      final j = i + rng.nextInt(indices.length - i);
      final tmp = indices[i];
      indices[i] = indices[j];
      indices[j] = tmp;
    }
    return List<String>.unmodifiable(
      [for (var i = 0; i < count; i++) all[indices[i]]],
    );
  }
